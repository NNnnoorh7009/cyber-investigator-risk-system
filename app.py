import streamlit as st

st.set_page_config(page_title="Cyber Investigator & CIA Triad", layout="centered")

st.title("نظام المحقق السيبراني وتقييم مخاطر CIA Triad")
st.write("إعداد: نوره علي آل فطيح")

st.markdown("---")

st.header("المحقق السيبراني")
scenario = st.selectbox(
    "اختر السيناريو السيبراني:",
    [
        "اختر سيناريو...",
        "تم تشفير الملفات والمطالبة بفدية (Ransomware)",
        "تم تسريب بيانات الموظفين على الإنترنت (Data Leak)",
        "الموقع الإلكتروني متوقف بسبب هجمات حجب الخدمة (DDoS)"
    ]
)

if scenario == "تم تشفير الملفات والمطالبة بفدية (Ransomware)":
    st.error("الخطر الرئيسي: التوافرية والسرية")
    st.info("التوصية: افصل الأجهزة المتأثرة عن الشبكة فوراً واسترجع النسخ الاحتياطية.")

elif scenario == "تم تسريب بيانات الموظفين على الإنترنت (Data Leak)":
    st.error("الخطر الرئيسي: السرية")
    st.info("التوصية: قم بتغيير كلمات المرور فوراً وتفعيل التحقق الثنائي.")

elif scenario == "الموقع الإلكتروني متوقف بسبب هجمات حجب الخدمة (DDoS)":
    st.error("الخطر الرئيسي: التوافرية")
    st.info("التوصية: تفعيل حماية وتصفية حركات المرور المشبوهة.")

st.markdown("---")

st.header("تقييم أبعاد مثلث أمن المعلومات")

c_val = st.slider("مستوى أهمية السرية", 1, 5, 3)
i_val = st.slider("مستوى أهمية السلامة والنزاهة", 1, 5, 3)
a_val = st.slider("مستوى أهمية التوافرية", 1, 5, 3)

total_score = c_val + i_val + a_val

if st.button("حساب تقييم المخاطر"):
    st.write(f"النتيجة الإجمالية للأهمية الأمنية: {total_score} / 15")
    if total_score >= 12:
        st.warning("مستوى خطورة مرتفع جداً: النظام يحتاج إلى ضوابط أمنية مشددة.")
    elif total_score >= 7:
        st.success("مستوى خطورة متوسط: الضوابط القياسية كافية مع المتابعة المستمرة.")
    else:
        st.info("مستوى خطورة منخفض: الحد الأدنى من الحماية الموصى بها كافٍ.")
